"""Refresh data/metadata.yaml from GitHub / Hugging Face.

Per link we record stars, created, pushed_at (or HF lastModified), archived, the
latest release, and fetched_at. Output is deterministic: sorted keys, and
fetched_at only moves when something else changed, so an unchanged week leaves
no diff. Set GITHUB_TOKEN to avoid the unauthenticated rate limit.
"""

import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import requests
import yaml

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Autogenerated by scripts/refresh.py; do not edit by hand.\n"


def _session() -> requests.Session:
    s = requests.Session()
    s.headers["Accept"] = "application/vnd.github+json"
    if token := os.environ.get("GITHUB_TOKEN"):
        s.headers["Authorization"] = f"Bearer {token}"
    return s


def fetch(link: str, s: requests.Session) -> dict:
    if link.startswith("https://huggingface.co/"):
        repo_id = link[len("https://huggingface.co/") :]
        if not repo_id.startswith(("datasets/", "models/")):
            repo_id = f"models/{repo_id}"  # bare ids are models
        r = s.get(f"https://huggingface.co/api/{repo_id}", timeout=30)
        r.raise_for_status()
        j = r.json()
        out = {"stars": j["likes"]}
        if j.get("createdAt"):
            out["created"] = j["createdAt"][:10]
        if j.get("lastModified"):
            out["pushed_at"] = j["lastModified"][:10]
        return out
    if link.startswith("https://github.com/"):
        repo_id = link[len("https://github.com/") :]
        r = s.get(f"https://api.github.com/repos/{repo_id}", timeout=30)
        r.raise_for_status()
        j = r.json()
        out = {
            "stars": j["stargazers_count"],
            "created": j["created_at"][:10],
            "pushed_at": j["pushed_at"][:10],
            "archived": bool(j["archived"]),
        }
        rel = s.get(
            f"https://api.github.com/repos/{repo_id}/releases/latest", timeout=30
        )
        if rel.status_code == 200:
            rj = rel.json()
            out["latest_release"] = {
                "tag": rj["tag_name"],
                "date": rj["published_at"][:10],
            }
        elif rel.status_code != 404:  # 404 just means no releases
            rel.raise_for_status()
        return out
    raise ValueError(f"unknown link type: {link}")


def merge(old: dict | None, new: dict, now: str) -> dict:
    """Keep the old fetched_at when nothing but the timestamp would change."""
    if old and {k: v for k, v in old.items() if k != "fetched_at"} == new:
        return old
    return {**new, "fetched_at": now}


def refresh(data_path: Path, meta_path: Path, s: requests.Session | None = None) -> int:
    s = s or _session()
    data = yaml.safe_load(data_path.read_text())
    meta = yaml.safe_load(meta_path.read_text()) if meta_path.exists() else {}
    meta = meta or {}
    links = sorted({e["link"] for items in data.values() for e in items})
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    failures = 0
    result = {}
    for link in links:
        try:
            result[link] = merge(meta.get(link), fetch(link, s), now)
        except Exception as e:  # keep the last good record rather than losing it
            failures += 1
            print(f"WARN {link}: {e}", file=sys.stderr)
            if link in meta:
                result[link] = meta[link]
    meta_path.write_text(
        HEADER + yaml.safe_dump(result, sort_keys=True, default_flow_style=False)
    )
    print(f"refreshed {len(links) - failures}/{len(links)} links")
    return failures


if __name__ == "__main__":
    refresh(ROOT / "data" / "data.yaml", ROOT / "data" / "metadata.yaml")
